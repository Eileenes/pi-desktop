export type TranslationKey = keyof typeof zhCN;

const dictionaries: Record<AppLanguage, Record<TranslationKey, string>> = {
	"zh-CN": zhCN,
	en,
};

// The module is also imported by Node-side tests, so DOM globals are optional.
const domStorage = (
	globalThis as {
		localStorage?: { getItem: (key: string) => string | null; setItem: (key: string, value: string) => void };
	}
).localStorage;
const domDocument = (globalThis as { document?: { documentElement: { lang: string } } }).document;

let currentLanguage: AppLanguage = (() => {
	try {
		return domStorage?.getItem("pi-desktop-language") === "en" ? "en" : "zh-CN";
	} catch {
		return "zh-CN";
	}
})();

const listeners = new Set<() => void>();

export function getAppLanguage(): AppLanguage {
	return currentLanguage;
}

export function setAppLanguage(language: AppLanguage): void {
	currentLanguage = language;
	try {
		domStorage?.setItem("pi-desktop-language", language);
		if (domDocument) domDocument.documentElement.lang = language;
	} catch {
		// Storage unavailable; language applies for this session only.
	}
	for (const listener of listeners) listener();
}

export function subscribeAppLanguage(listener: () => void): () => void {
	listeners.add(listener);
	return () => listeners.delete(listener);
}

export function translate(
	language: AppLanguage,
	key: TranslationKey,
	params?: Record<string, string | number>,
): string {
	const template = dictionaries[language][key] ?? dictionaries["zh-CN"][key] ?? key;
	if (!params) return template;
	return template.replace(/\{(\w+)\}/gu, (match, name: string) =>
		Object.hasOwn(params, name) ? String(params[name]) : match,
	);
}

export interface I18n {
	language: AppLanguage;
	t: (key: TranslationKey, params?: Record<string, string | number>) => string;
	setLanguage: (language: AppLanguage) => void;
}

export function useI18n(): I18n {
	useSyncExternalStore(subscribeAppLanguage, getAppLanguage, getAppLanguage);
	return {
		language: currentLanguage,
		t: (key, params) => translate(currentLanguage, key, params),
		setLanguage: setAppLanguage,
	};
}
